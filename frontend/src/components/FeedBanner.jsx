import { RadioTower, TriangleAlert, CloudOff, FlaskConical, RefreshCw } from 'lucide-react';

/**
 * Presentation for each feed state. `live` intentionally has no entry: a healthy
 * device needs no banner, and the Header chip already reports it.
 */
const STATES = {
  disconnected: {
    tone: 'border-red-300 bg-red-50',
    ink: 'text-red-700',
    sub: 'text-red-700/70',
    Icon: CloudOff,
    title: 'Backend unreachable',
    detail: 'The WatLab server is not responding. Values are frozen at their last known reading.'
  },
  stale: {
    tone: 'border-red-300 bg-red-50',
    ink: 'text-red-700',
    sub: 'text-red-700/70',
    Icon: TriangleAlert,
    title: 'Device offline',
    detail: 'No telemetry received. Gauges are frozen and will refresh automatically.'
  },
  waiting: {
    tone: 'border-amber-300 bg-amber-50',
    ink: 'text-amber-700',
    sub: 'text-amber-700/70',
    Icon: RadioTower,
    title: 'Waiting for WatLab hardware telemetry',
    detail: 'Broker link is being established. No measurement is displayed until the device publishes.'
  },
  simulated: {
    tone: 'border-brand-300 bg-brand-50',
    ink: 'text-brand-700',
    sub: 'text-brand-700/70',
    Icon: FlaskConical,
    title: 'Virtual plant — simulated feed',
    detail: 'No ESP32 data. These values are generated by the demo engine, not measured on site.'
  }
};

function ageLabel(ageSec) {  if (ageSec == null) return null;
  if (ageSec < 60) return `${ageSec}s`;
  const m = Math.floor(ageSec / 60);
  if (m < 60) return `${m} min ${ageSec % 60} s`;
  const h = Math.floor(m / 60);
  return `${h} h ${m % 60} min`;
}

/** Lets the shell avoid reserving margin for a banner that renders nothing. */
export function hasFeedNotice(feed) {
  return feed?.status !== 'live';
}

/**
 * Renders nothing while the feed is live. Every other state gets an explicit,
 * non-alarming explanation of what the operator is looking at.
 */
export default function FeedBanner({ feed, broker }) {
  const state = STATES[feed.status];
  if (!state) return null;

  const { Icon } = state;
  const stale = ageLabel(feed.ageSec);
  const showRetry = feed.status === 'stale' || feed.status === 'disconnected';

  return (
    <div className={`rounded-lg border p-3.5 ${state.tone}`}>
      <div className="flex items-start gap-2.5">
        <Icon className={`mt-0.5 h-4 w-4 shrink-0 ${state.ink}`} />

        <div className="min-w-0 flex-1">
          <p className={`text-[12.5px] font-semibold ${state.ink}`}>{state.title}</p>
          <p className={`mt-0.5 text-[11px] leading-4 ${state.sub}`}>{state.detail}</p>

          {(stale || broker?.error) && (
            <div className={`mt-2 flex flex-wrap items-center gap-x-3 gap-y-1 font-mono text-[10px] ${state.sub}`}>
              {stale && <span>last packet {stale} ago</span>}
              {broker?.error && <span className="truncate">broker: {broker.error}</span>}
              {showRetry && (
                <span className="inline-flex items-center gap-1">
                  <RefreshCw className="h-3 w-3 animate-spin" />
                  retrying automatically
                </span>
              )}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
